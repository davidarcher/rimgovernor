using RimGovernor.Brain.GameFacts.Observations;

namespace RimGovernor.Brain.Policy;

/// <summary>A demand-independent visit on an exact safe native pack; purchase authorization follows selection.</summary>
public sealed record ForecastSettlementMission(string Settlement, EquatableArray<string> Crew, double Days, EquatableArray<TradeSource> Sources)
{
    public string Id => "trade/mission/" + Settlement;
    public ForecastCommitment Commitment() => new(Id, []) { TradeMission = Id, ExclusiveOutcome = "trade/mission" };
}

public static class ForecastSettlementMissions
{
    /// <summary>Held stock is priced as read until the native restock; later arrivals and unseen stock use the kind's generators.
    /// No stock is generated by this calculation. It promises availability at home, never secured delivery.</summary>
    public static ForecastSettlementMission? Option(TraderStockTable catalog, Settlement settlement, TradePackEstimate pack,
        IReadOnlyList<string> crew, long silver)
    {
        if (!settlement.CanTrade || settlement.Relation is SettlementRelation.Player or SettlementRelation.Hostile
            || crew.Count == 0 || silver <= 0 || pack is not TradePackEstimate.Packed packed || !TradePolicyRules.SafeTradeMissionPack(pack)) return null;
        var read = packed.SettlementTrade ?? throw new RequiredFactException("settlement_trade_preview:" + settlement.Id);
        if (read.Settlement != settlement.Id || read.TraderKind != settlement.TraderKind || read.RestockInTicks < 0
            || !double.IsFinite(read.PriceFactor)) throw new RequiredFactException("settlement_trade_preview:" + settlement.Id);
        if (!catalog.Kinds.TryGetValue(read.TraderKind, out var kind)) throw new RequiredFactException("trader_kind_unknown:" + read.TraderKind);
        if (kind.Favor) return null;
        var (days, _) = TradePolicyRules.TradeMissionRouteDays(packed);
        var outbound = ((PackRoute.Reachable)packed.Outbound).EstimatedTicks;
        IEnumerable<TradeSource> sources;
        if (read.RegeneratesOnVisit || outbound >= read.RestockInTicks)
            sources = kind.Offers.OrderBy(o => o.Key.Value, StringComparer.Ordinal).Select(o =>
                new TradeSource(o.Key, days, 0) { Once = true, Kinds = [new(1, o.Value)], Silver = silver, PriceFactor = read.PriceFactor });
        else
            sources = read.CurrentStock.GroupBy(s => s.Definition, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal).Select(g =>
            {
                if (g.Any(s => s.Count <= 0 || !double.IsFinite(s.UnitPrice) || s.UnitPrice <= 0)) throw new RequiredFactException("settlement_stock:" + settlement.Id);
                var count = g.Sum(s => s.Count);
                // A definition's mixed stacks use the highest observed unit price, a conservative affordability bound.
                var offer = new TraderOffer { UnitValue = g.Max(s => s.UnitPrice), Draws = [new(1, 1, 1, 1, count, count, 0, 0, 1)] };
                return new TradeSource(new(g.Key), days, 0) { Once = true, Kinds = [new(1, offer)], Silver = silver, PriceFactor = 1 };
            });
        return new(settlement.Id, EquatableArray.From(crew), days, EquatableArray.From(sources));
    }

    internal static double LostWork(ForecastSettlementMission mission, ForecastCoupledOutcome outcome,
        IReadOnlyList<ForecastCommitment> chosen, ForecastCoupledContext context, double horizon)
    {
        if (context.InvestmentHorizonDays <= 0 || mission.Days <= 0) return 0;
        var shortfall = JoinerMoodRules.ShortfallOf(outcome, chosen, context, horizon);
        var free = PawnValueRules.FreeHoursOf(outcome, context);
        double days = 0;
        foreach (var id in mission.Crew)
        {
            var pawn = context.Needs.Pawns.SingleOrDefault(p => p.Pawn == id) ?? throw new RequiredFactException("trade_mission_pawn:" + id);
            if (!free.TryGetValue(id, out var hours)) throw new RequiredFactException("free hours of " + id);
            days += PawnValueRules.WorkAdded(new(id)
            {
                Speeds = pawn.Upkeep.Speeds.ToDictionary(s => s.Stat, s => s.Value, StringComparer.Ordinal),
                Incapable = pawn.Upkeep.IncapableWork, FreeTicksPerDay = hours * GameTime.TicksPerHour,
            }, shortfall).Sum(w => w.TicksPerDay) / GameTime.TicksPerDay * Math.Min(mission.Days, context.InvestmentHorizonDays);
        }
        return days;
    }
}
