using System.Reflection;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace RimGovernor.Brain.Policy;

/// <summary>Whether a probe has confirmed a mechanic card. Only <see cref="Verified"/> cards may drive live play (#3217).</summary>
public enum MechanicCardStatus
{
    [JsonStringEnumMemberName("extracted")]
    Extracted,

    [JsonStringEnumMemberName("verified")]
    Verified,

    /// <summary>
    /// Every site has a guard no writer on its direct caller path can make hold (#3243). It ships so the lever is known
    /// dead; it is never live and a probe cannot verify it.
    /// </summary>
    [JsonStringEnumMemberName("unreachable")]
    Unreachable,
}

/// <summary>mechanic_cards.json: the cards of the ThoughtDefs with a live consumer, generated by <c>RimGovernor.cmd thoughtaudit -guards</c>.</summary>
public sealed record MechanicCardFile(int Schema, IReadOnlyList<MechanicCard> Cards);

/// <summary>One ThoughtDef's mechanic: its XML data, the code sites that grant it, their guards and the writers of the fields they read.</summary>
public sealed record MechanicCard(string Def, MechanicCardStatus Status, MechanicCardXml Xml, IReadOnlyList<MechanicCardSite> Sites)
{
    /// <summary>False for a card no probe has verified: it is loaded, but consumers ignore it for live play.</summary>
    [JsonIgnore]
    public bool Live => Status == MechanicCardStatus.Verified;
}

/// <summary>The def's XML fields.</summary>
public sealed record MechanicCardXml(IReadOnlyList<string> NullifyingTraits, IReadOnlyList<MechanicCardStage> Stages)
{
    /// <summary>The HediffDefs whose presence nullifies the thought (#3281); empty when the XML lists none.</summary>
    public IReadOnlyList<string> NullifyingHediffs { get; init; } = [];
}

/// <summary>A stage's <c>baseMoodEffect</c>; the card file writes the game's field default, 0, for a stage whose XML lists none.</summary>
public sealed record MechanicCardStage(double BaseMoodEffect);

/// <summary>
/// A granting member and the guards on its path. <see cref="Stage"/> is set when the site returns a banded stage (#3324).
/// </summary>
public sealed record MechanicCardSite(string Site, IReadOnlyList<MechanicCardGuard> Guards, IReadOnlyList<MechanicCardField> Writers, MechanicCardStageBand? Stage = null);

/// <summary>
/// The stage a site returns over a traced input (#3324): the <see cref="MechanicCardThreshold.Stage"/> of the first of the
/// ascending <see cref="Thresholds"/> whose <see cref="MechanicCardThreshold.Below"/> the <see cref="Input"/> is under, else
/// <see cref="Else"/>; then each modifier's <see cref="MechanicCardModifier.Delta"/> whose condition holds is added. The site's
/// guards still say when the thought is active at all (for example a negative stage is inactive).
/// </summary>
public sealed record MechanicCardStageBand(MechanicCardExpr Input, IReadOnlyList<MechanicCardThreshold> Thresholds, int Else, IReadOnlyList<MechanicCardModifier> Modifiers);

public sealed record MechanicCardThreshold(double Below, int Stage);

/// <summary>A stage shift: <see cref="Delta"/> applies when <see cref="When"/> holds.</summary>
public sealed record MechanicCardModifier(MechanicCardExpr When, double Delta);

/// <summary>
/// One condition on the path to a site or writer. A count guard (#3281) carries <see cref="Count"/>, and its Expr compares the
/// count symbol (kind <c>count</c>) with literals.
/// </summary>
public sealed record MechanicCardGuard(MechanicCardExpr Expr, MechanicCardCount? Count = null);

/// <summary>
/// What a count guard counts (#3281): the elements of <see cref="Over"/> for which <see cref="Where"/> holds; <see cref="Stage"/>
/// is the stage index the site returns, as an expression over the count.
/// </summary>
public sealed record MechanicCardCount(MechanicCardExpr Over, MechanicCardExpr Where, MechanicCardExpr Stage);

/// <summary>
/// A guard expression node: a symbol (Kind, Decl), a literal (<see cref="Lit"/>) or an operator over <see cref="Args"/>
/// (<see cref="Op"/>).
/// </summary>
public sealed record MechanicCardExpr(
    string? Kind = null,
    string? Decl = null,
    string? Lit = null,
    string? Op = null,
    IReadOnlyList<MechanicCardExpr>? Args = null);

/// <summary>The writers of a field a guard reads. Follows are the fields a writer copies from. <c>thoughtaudit</c> checks the decls of their guards against the game sources.</summary>
public sealed record MechanicCardField(string Field, IReadOnlyList<MechanicCardWriter> Writers, IReadOnlyList<MechanicCardField> Follows);

/// <summary>One write of a field: the guards on its path.</summary>
public sealed record MechanicCardWriter(IReadOnlyList<MechanicCardGuard> Guards);

/// <summary>The embedded card catalog, loaded on first use. A malformed or unknown-schema file throws instead of yielding an empty catalog.</summary>
public static class MechanicCards
{
    /// <summary>The card file schema; 2 adds the site stage band (#3324).</summary>
    public const int Schema = 2;

    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
        RespectNullableAnnotations = true,
        RespectRequiredConstructorParameters = true,
        Converters = { new JsonStringEnumConverter<MechanicCardStatus>(namingPolicy: null, allowIntegerValues: false) },
    };

    private static readonly Lazy<IReadOnlyDictionary<string, MechanicCard>> Embedded = new(LoadEmbedded);

    /// <summary>All embedded cards by def.</summary>
    public static IReadOnlyDictionary<string, MechanicCard> ByDef => Embedded.Value;

    private static IReadOnlyDictionary<string, MechanicCard> LoadEmbedded()
    {
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("mechanic_cards.json")
            ?? throw new DomainException("mechanic_cards.json is not embedded in the policy assembly");
        return Parse(stream);
    }

    /// <summary>
    /// Parses a card file into cards by def: malformed JSON, an unknown or missing field or status throws
    /// <see cref="JsonException"/>; another schema or a duplicate def throws <see cref="DomainException"/>.
    /// </summary>
    public static IReadOnlyDictionary<string, MechanicCard> Parse(Stream json)
    {
        var file = JsonSerializer.Deserialize<MechanicCardFile>(json, Options);
        if (file is null || file.Schema != Schema)
        {
            throw new DomainException($"mechanic_cards.json has schema {file?.Schema}, expected {Schema}");
        }
        var cards = new Dictionary<string, MechanicCard>(StringComparer.Ordinal);
        foreach (var card in file.Cards)
        {
            if (!cards.TryAdd(card.Def, card))
            {
                throw new DomainException("mechanic_cards.json lists " + card.Def + " twice");
            }
        }
        return cards;
    }
}
