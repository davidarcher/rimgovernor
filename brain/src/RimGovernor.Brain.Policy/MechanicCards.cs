using System.Reflection;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace RimGovernor.Brain.Policy;

/// <summary>Whether a probe has confirmed a mechanic card. Only <see cref="Verified"/> cards may drive live play (#3217).</summary>
public enum MechanicCardStatus
{
    [JsonStringEnumMemberName("extracted")]
    Extracted,

    [JsonStringEnumMemberName("verified")]
    Verified,

    /// <summary>
    /// Every site has a guard no writer on its direct caller path can make hold (#3243). It ships so the lever is known
    /// dead; it is never live and a probe cannot verify it.
    /// </summary>
    [JsonStringEnumMemberName("unreachable")]
    Unreachable,
}

/// <summary>mechanic_cards.json: the cards of the ThoughtDefs with a live consumer, generated by <c>RimGovernor.cmd thoughtaudit -guards</c>.</summary>
public sealed record MechanicCardFile(int Schema, string Game, IReadOnlyList<MechanicCard> Cards);

/// <summary>One ThoughtDef's mechanic: its XML data, the code sites that grant it, their guards and the writers of the fields they read.</summary>
public sealed record MechanicCard(string Def, string Kind, MechanicCardStatus Status, MechanicCardXml Xml, IReadOnlyList<MechanicCardSite> Sites)
{
    /// <summary>False for a card no probe has verified: it is loaded, but consumers ignore it for live play.</summary>
    [JsonIgnore]
    public bool Live => Status == MechanicCardStatus.Verified;
}

/// <summary>The def's XML fields; a number absent from the XML is null (the game's default applies).</summary>
public sealed record MechanicCardXml(IReadOnlyList<string> NullifyingTraits, IReadOnlyList<MechanicCardStage> Stages, double? DurationDays = null, int? StackLimit = null, double? StackedEffectMultiplier = null)
{
    /// <summary>The HediffDefs whose presence nullifies the thought (#3281); empty when the XML lists none.</summary>
    public IReadOnlyList<string> NullifyingHediffs { get; init; } = [];
}

public sealed record MechanicCardStage(double? BaseMoodEffect = null);

/// <summary>A granting member, with its access, caller count and drift hash (<see cref="BodyHash"/>, of the member's normalized syntax).</summary>
public sealed record MechanicCardSite(string Site, string BodyHash, string Access, int Callers, IReadOnlyList<MechanicCardGuard> Guards, IReadOnlyList<MechanicCardField> Writers);

/// <summary>
/// One condition on the path to a site or writer; <see cref="Origin"/> is the syntax it came from (early-exit, if, foreach, ...).
/// <see cref="Unreachable"/>, when set, says why no writer on the site's direct caller path can make it hold (#3243).
/// A count guard (origin <c>count</c>, #3281) carries <see cref="Count"/>, and its Expr compares the count symbol (kind <c>count</c>) with literals.
/// </summary>
public sealed record MechanicCardGuard(string Origin, MechanicCardExpr Expr, string? Unreachable = null, MechanicCardCount? Count = null);

/// <summary>
/// What a count guard counts (#3281): the elements of <see cref="Over"/> for which <see cref="Where"/> holds; <see cref="Stage"/>
/// is the stage index the site returns, as an expression over the count. <see cref="Via"/> names the worker override the
/// predicate was resolved through, and <see cref="ViaHash"/> is its drift hash.
/// </summary>
public sealed record MechanicCardCount(MechanicCardExpr Over, MechanicCardExpr Where, MechanicCardExpr Stage, string? Via = null, string? ViaHash = null);

/// <summary>
/// A guard expression node: a symbol (<see cref="Sym"/> with Kind, Decl, Type), a literal (<see cref="Lit"/>), an
/// operator over <see cref="Args"/> (<see cref="Op"/>), or an unresolved leaf (<see cref="Unknown"/> is the reason, Text the source).
/// </summary>
public sealed record MechanicCardExpr(
    string? Sym = null,
    string? Kind = null,
    string? Decl = null,
    string? Type = null,
    string? Lit = null,
    string? Unknown = null,
    string? Text = null,
    string? Op = null,
    IReadOnlyList<MechanicCardExpr>? Args = null);

/// <summary>The writers of a field a guard reads; <see cref="WritersFound"/> exceeds the listed writers when the tool capped them. Follows are the fields a writer copies from.</summary>
public sealed record MechanicCardField(string Field, string Kind, int WritersFound, int ResetWriters, IReadOnlyList<MechanicCardWriter> Writers, IReadOnlyList<MechanicCardField> Follows);

/// <summary>One write of a field: the method and its drift hash, the write kind (set, serialization, ref-arg, reset, ...), the value and the guards on its path.</summary>
public sealed record MechanicCardWriter(string Method, string BodyHash, string Write, string Value, IReadOnlyList<MechanicCardGuard> Guards, bool ReceiverUnresolved = false);

/// <summary>The embedded card catalog, loaded on first use. A malformed or unknown-schema file throws instead of yielding an empty catalog.</summary>
public static class MechanicCards
{
    public const int Schema = 1;

    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,
        RespectNullableAnnotations = true,
        RespectRequiredConstructorParameters = true,
        Converters = { new JsonStringEnumConverter<MechanicCardStatus>(namingPolicy: null, allowIntegerValues: false) },
    };

    private static readonly Lazy<IReadOnlyDictionary<string, MechanicCard>> Embedded = new(LoadEmbedded);

    /// <summary>All embedded cards by def.</summary>
    public static IReadOnlyDictionary<string, MechanicCard> ByDef => Embedded.Value;

    private static IReadOnlyDictionary<string, MechanicCard> LoadEmbedded()
    {
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("mechanic_cards.json")
            ?? throw new DomainException("mechanic_cards.json is not embedded in the policy assembly");
        return Parse(stream);
    }

    /// <summary>
    /// Parses a card file into cards by def: malformed JSON, an unknown or missing field or status throws
    /// <see cref="JsonException"/>; another schema or a duplicate def throws <see cref="DomainException"/>.
    /// </summary>
    public static IReadOnlyDictionary<string, MechanicCard> Parse(Stream json)
    {
        var file = JsonSerializer.Deserialize<MechanicCardFile>(json, Options);
        if (file is null || file.Schema != Schema)
        {
            throw new DomainException($"mechanic_cards.json has schema {file?.Schema}, expected {Schema}");
        }
        var cards = new Dictionary<string, MechanicCard>(StringComparer.Ordinal);
        foreach (var card in file.Cards)
        {
            if (!cards.TryAdd(card.Def, card))
            {
                throw new DomainException("mechanic_cards.json lists " + card.Def + " twice");
            }
        }
        return cards;
    }
}
